// One-off (step 1a of the Vite split): copy throttle-up-v11.html verbatim into
//   index.html      head (meta, title, import map) + body markup
//   src/style.css   the <style> block
//   src/legacy.js   script 1 + script 2, concatenated into one ES module, plus a generated test bridge
// Re-runnable: it always starts from the v11 file. Deleted at the end of the split.

import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from '@babel/parser';
import traverseMod from '@babel/traverse';

const traverse = traverseMod.default || traverseMod;
const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const src = (await readFile(resolve(ROOT, 'throttle-up-v11.html'), 'utf8')).replace(/\r\n/g, '\n');
const L = src.split('\n');
const lines = (a, b) => L.slice(a - 1, b).join('\n');   // 1-based, inclusive

// Sanity checks on the line ranges, so a changed v11 file fails loudly instead of being cut wrongly.
const expect = (n, s) => { if (L[n - 1] !== s) throw new Error(`line ${n}: expected ${JSON.stringify(s)}, got ${JSON.stringify(L[n - 1].slice(0, 60))}`); };
expect(6, '<style>'); expect(50, '</style></head><body>'); expect(59, '<script>'); expect(1094, '</script>');
expect(1095, '<script>'); expect(2020, '</script></body></html>');

const html = `${lines(1, 5)}
<link rel="stylesheet" href="/src/style.css">
</head><body>
${lines(51, 58)}
<script type="module" src="/src/main.js"></script>
</body></html>
`;

const script1 = lines(60, 1093), script2 = lines(1096, 2019);
const code = `${script1}\n${script2}\n`;

// Test bridge: in v11 the scripts were classic, so tests could read and assign every top-level name from
// page.evaluate. In a module those names are module-scoped; expose each one on window through an accessor.
const ast = parse(code, { sourceType: 'module' });
const names = [];
traverse(ast, { Program(p) { for (const [name, b] of Object.entries(p.scope.bindings)) names.push([name, b.kind]); p.stop(); } });
const entries = names.map(([n, kind]) => kind === 'const' ? `d('${n}',()=>${n})` : `d('${n}',()=>${n},v=>{${n}=v})`);
const bridge = `
/* ---------- test bridge (generated by tools/split/extract.mjs): tests read and assign these names on window, as they could when the scripts were classic ---------- */
{const d=(k,g,s)=>{const o=Object.getOwnPropertyDescriptor(window,k);if(o&&!o.configurable){console.error('test bridge: cannot expose '+k);return}Object.defineProperty(window,k,{get:g,set:s,configurable:true})};
${entries.join(';')}}
`;

await mkdir(resolve(ROOT, 'src'), { recursive: true });
await writeFile(resolve(ROOT, 'index.html'), html);
await writeFile(resolve(ROOT, 'src/style.css'), lines(7, 49) + '\n');
await writeFile(resolve(ROOT, 'src/legacy.js'), code + bridge);
await writeFile(resolve(ROOT, 'src/main.js'), `// Entry point. During the split everything still lives in legacy.js (v11's two scripts, verbatim).\nimport './legacy.js';\n`);
const kinds = names.reduce((m, [, k]) => (m[k] = (m[k] || 0) + 1, m), {});
console.log(`index.html, src/style.css, src/main.js, src/legacy.js written; bridge exposes ${names.length} names`, kinds);
